async function main() {
  const sql = postgres(process.env.DATABASE_URL, { prepare: false });
  try {
    for (const [i, c] of CARDS.entries()) {
      if (!c.front || !c.back || !Array.isArray(c.conceptTags)) {
        throw new Error(`malformed card at index ${i}: ${JSON.stringify(c)}`);
      }
    }

    await sql`DELETE FROM srs_cards WHERE user_id IS NULL AND source_trade_id IS NULL`;
    // postgres.js's bulk sql(rows, ...cols) helper mishandles array-typed
    // columns (reproduced independently: even a single row with an array
    // value throws UNDEFINED_VALUE through that helper) — inserting one row
    // at a time with a plain interpolated array works fine and 60 rows is
    // small enough that this costs nothing noticeable.
    for (const c of CARDS) {
      await sql`INSERT INTO srs_cards (front, back, concept_tags) VALUES (${c.front}, ${c.back}, ${c.conceptTags})`;
    }
    console.log(`seeded ${CARDS.length} shared SRS cards`);
  } finally {
    await sql.end();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
